def _g_single_call(rec, tools) -> str:
    return _hdr("Single model call: retrieval in code, then one answer.") + textwrap.dedent('''\
        from langgraph.graph import END, START, StateGraph

        from .agents import chat_model
        from .state import State

        SYSTEM = "TODO: system prompt. State the task, the audience and the output format."


        def retrieve(state: State) -> dict:
            """TODO: deterministic retrieval in code (classic RAG). Return context for the prompt."""
            return {"messages": [("system", SYSTEM)]}


        def answer(state: State) -> dict:
            llm = chat_model("llm")
            msg = llm.invoke([("system", SYSTEM), ("user", state["request"])])
            return {"answer": msg.content if isinstance(msg.content, str) else str(msg.content), "messages": [msg]}


        def build_graph():
            g = StateGraph(State)
            g.add_node("retrieve", retrieve)
            g.add_node("answer", answer)
            g.add_edge(START, "retrieve")
            g.add_edge("retrieve", "answer")
            g.add_edge("answer", END)
            return g.compile()
        ''')


