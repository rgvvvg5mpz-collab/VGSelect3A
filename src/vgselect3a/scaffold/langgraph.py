def slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    return s or "app"


def ident(name: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9]+", "_", name).strip("_").lower()
    if not s or s[0].isdigit():
        s = "n_" + s
    return s


def _tools(rec: "Recommendation") -> list[str]:
    p = rec.profile
    given = p.extra.get("tools") if isinstance(p.extra.get("tools"), list) else []
    names = [ident(str(t)) for t in given if str(t) and not str(t).startswith("~")]
    if not names and p.uses_tools:
        names = [f"tool_{i + 1}" for i in range(min(p.tool_count, 5))]
    seen, out = set(), []
    for n in names:
        if n not in seen:
            seen.add(n); out.append(n)
    return out[:20]


def generate(rec: "Recommendation") -> dict[str, str]:
    p = rec.profile
    topo = rec.primary.topology.id
    tools = _tools(rec)
    comps = rec.plan.components
    files: dict[str, str] = {}
    files["README.md"] = _readme(rec, topo, tools)
    files["ARCHITECTURE.md"] = rec.to_markdown()
    files["vgselect_profile.json"] = p.to_json()
    files["requirements.txt"] = "langgraph>=0.2\nlangchain>=0.3\nlangchain-core>=0.3\nlangchain-anthropic>=0.3\npython-dotenv>=1.0\npytest>=8\n"
    files[".env.example"] = "ANTHROPIC_API_KEY=sk-ant-...\n"
    files[".gitignore"] = ".env\n__pycache__/\n*.pyc\n.venv/\n"
    files["app/__init__.py"] = ""
    files["app/config.py"] = _config(rec, comps)
    files["app/tools.py"] = _tools_py(tools, p)
    files["app/agents.py"] = _agents_py()
    files["app/state.py"] = _state_py(topo)
    files["app/graph.py"] = _GRAPH[topo](rec, tools)
    files["main.py"] = _main_py(topo)
    files["tests/test_graph.py"] = _test_py()
    return files


