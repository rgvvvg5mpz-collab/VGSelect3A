def _config(rec, comps) -> str:
    p = rec.profile
    roles = "\n".join(f'    "{ident(c.id)}": Role(name={c.name!r}, model={c.model_id!r}, effort={c.effort!r}, tier={c.tier!r}),' for c in comps)
    return textwrap.dedent(f'''\
    """Models, effort and limits per role. Generated from the VG Select: 3A plan."""

    from dataclasses import dataclass


    @dataclass(frozen=True)
    class Role:
        name: str
        model: str
        effort: str
        tier: str


    # Model IDs are current-generation defaults; substitute your approved equivalents.
    ROLES: dict[str, Role] = {{
    {roles}
    }}

    # Termination limits (MAST: "unaware of termination" and step repetition are ~28% of multi-agent failures).
    RECURSION_LIMIT = {max(25, min(200, int(p.tool_calls_per_task) * 3 + 20))}   # LangGraph steps per request
    MAX_TOOL_CALLS = {max(3, int(p.tool_calls_per_task) or 3)}          # per agent per request
    MAX_ITERATIONS = {3 if p.accuracy_priority >= 5 else 2}             # evaluator / refinement loops
    MAX_WORKERS = {worker_count(p) if rec.primary.topology.id in ('orchestrator_workers', 'hierarchical') else max(2, min(p.parallel_subtasks, 20))}
    LATENCY_BUDGET_S = {p.latency_budget_s}

    # Thinking / effort: langchain-anthropic passes provider params through model_kwargs.
    # Adaptive thinking is the default on current Claude models; tune effort per role, e.g.
    #   ChatAnthropic(model=..., model_kwargs={{"output_config": {{"effort": "high"}}}})
    DEFAULT_MAX_TOKENS = 4096
    ''')


def _tools_py(tools, p) -> str:
    stubs = "\n\n".join(textwrap.dedent(f'''\
        @tool
        def {t}(query: str) -> str:
            """TODO: describe precisely what `{t}` does, its inputs and what it returns.
            Agents choose tools by this description."""
            # TODO: implement
            return f"{t} result for: {{query}}"''') for t in tools) or textwrap.dedent('''\
        # No tools were declared in the profile. Add @tool functions here and list them in TOOLS.''')
    gate = ""
    if p.tool_side_effects == "irreversible":
        gate = textwrap.dedent('''\

        IRREVERSIBLE = {  # TODO: list tool names whose effects cannot be undone
        }


        def requires_approval(tool_name: str) -> bool:
            """Wire this into an interrupt (langgraph.types.interrupt) or a human approval step
            before executing irreversible tools."""
            return tool_name in IRREVERSIBLE
        ''')
    return textwrap.dedent('''\
        """Tool definitions. Keep tools few, distinct and well described."""

        from langchain_core.tools import tool


        ''') + stubs + "\n\n\nTOOLS = [" + ", ".join(tools) + "]\n" + gate


def _agents_py() -> str:
    return textwrap.dedent('''\
        """Role agent factory. Uses langchain's create_agent (LangChain 1.x) with a fallback to
        langgraph.prebuilt.create_react_agent (LangGraph 0.2/0.3)."""

        from langchain_anthropic import ChatAnthropic

        from .config import DEFAULT_MAX_TOKENS, ROLES

        try:  # LangChain 1.x
            from langchain.agents import create_agent as _create_agent

            def _build(model, tools, system_prompt):
                return _create_agent(model, tools=tools, system_prompt=system_prompt)
        except ImportError:  # LangGraph 0.2 / 0.3
            from langgraph.prebuilt import create_react_agent as _create_react_agent

            def _build(model, tools, system_prompt):
                return _create_react_agent(model, tools, prompt=system_prompt)


        def chat_model(role_id: str, **kwargs) -> ChatAnthropic:
            role = ROLES[role_id]
            return ChatAnthropic(model=role.model, max_tokens=kwargs.pop("max_tokens", DEFAULT_MAX_TOKENS), **kwargs)


        def role_agent(role_id: str, system_prompt: str, tools=None):
            """A tool-using agent for one role of the plan."""
            return _build(chat_model(role_id), list(tools or []), system_prompt)


        def last_text(result) -> str:
            """Final assistant text from an agent/graph result."""
            msgs = result["messages"] if isinstance(result, dict) else result
            for m in reversed(msgs):
                content = getattr(m, "content", None)
                if getattr(m, "type", "") == "ai" and content:
                    if isinstance(content, list):
                        return "".join(b.get("text", "") for b in content if isinstance(b, dict))
                    return str(content)
            return ""
        ''')


def _state_py(topo) -> str:
    extra = {
        "router": "    route: str\n",
        "parallel_sectioning": "    sections: list[str]\n    results: Annotated[list[str], operator.add]\n",
        "parallel_voting": "    votes: Annotated[list[str], operator.add]\n",
        "evaluator_optimizer": "    draft: str\n    feedback: str\n    accepted: bool\n    iteration: int\n",
        "orchestrator_workers": "    plan: list[dict]\n    reports: Annotated[list[str], operator.add]\n    draft: str\n",
        "hierarchical": "    domains: list[str]\n    domain_reports: Annotated[list[str], operator.add]\n",
        "handoff_network": "    active: str\n    handoffs: int\n",
        "prompt_chain": "    outline: str\n    draft: str\n    checked: bool\n",
    }.get(topo, "")
    return textwrap.dedent('''\
        """Graph state."""

        import operator
        from typing import Annotated, TypedDict

        from langchain_core.messages import AnyMessage
        from langgraph.graph.message import add_messages


        class State(TypedDict, total=False):
            request: str
            messages: Annotated[list[AnyMessage], add_messages]
            answer: str
        ''') + extra


